#!/usr/bin/env python3
"""Fetch and verify the pinned AMD FSR SDK for the Windows Vulkan build.

Every file listed in fsr-sdk.json is downloaded from the tagged SDK sources
and checked against its SHA-256 before use. The script can then:

- install the FidelityFX API headers into an engine tree
  (thirdparty/amd-fsr-sdk), together with fsr_sdk_runtime.gen.h, which pins the
  DLL names and hashes the engine verifies before loading them;
- copy the signed Vulkan runtime DLLs and the SDK licence files into an output
  directory (the licences go to <output>/licenses/AMD-FidelityFX).

Usage:
    prepare_fsr_sdk.py --cache CACHE_DIR [--engine ENGINE_TREE] [--output DLL_DIR]
"""

import argparse
import hashlib
import json
import shutil
import sys
import urllib.request
from pathlib import Path, PurePosixPath

MANIFEST = Path(__file__).with_name("fsr-sdk.json")
HEADER_PREFIX = "Kits/FidelityFX/"


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for block in iter(lambda: source.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def safe_member(name: str) -> PurePosixPath:
    member = PurePosixPath(name)
    if member.is_absolute() or ".." in member.parts:
        raise ValueError(f"Unsafe SDK path: {name}")
    return member


def fetch(cache: Path, base_url: str, name: str, expected: str) -> Path:
    path = cache.joinpath(*safe_member(name).parts)
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_name(path.name + ".download")
        print(f"Downloading {name}")
        with urllib.request.urlopen(base_url + name, timeout=300) as source, temporary.open("wb") as target:
            shutil.copyfileobj(source, target)
        if sha256_file(temporary) != expected:
            temporary.unlink()
            raise ValueError(f"AMD FSR SDK checksum mismatch: {name}")
        temporary.replace(path)
    actual = sha256_file(path)
    if actual != expected:
        raise ValueError(f"AMD FSR SDK checksum mismatch: {name} ({actual})")
    return path


def runtime_header(manifest: dict) -> str:
    lines = [
        "// Generated by tools/engine/prepare_fsr_sdk.py from fsr-sdk.json. Do not edit.",
        "#pragma once",
        "",
        f'#define FSR_SDK_PINNED_VERSION "{manifest["version"]}"',
        "",
        "struct FSRSDKRuntimeFile {",
        "\tconst char *name;",
        "\tconst char *sha256;",
        "};",
        "",
        "// Loader last: effect DLLs are verified before the loader can pull them in.",
        "static const FSRSDKRuntimeFile FSR_SDK_RUNTIME_FILES[] = {",
    ]
    ordered = sorted(manifest["runtime"], key=lambda dll: "loader" in dll)
    for dll in ordered:
        lines.append(f'\t{{ "{dll}", "{manifest["files"]["Kits/FidelityFX/signedbin/" + dll]}" }},')
    lines += ["};", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--cache", type=Path, required=True, help="Download cache (files are reused when their hash matches)")
    parser.add_argument("--engine", type=Path, help="Godot source tree that receives thirdparty/amd-fsr-sdk")
    parser.add_argument("--output", type=Path, help="Directory that receives the runtime DLLs and licences")
    args = parser.parse_args()

    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    files = {name: fetch(args.cache, manifest["base_url"], name, expected) for name, expected in manifest["files"].items()}
    for dll in manifest["runtime"]:
        if f"Kits/FidelityFX/signedbin/{dll}" not in files:
            raise ValueError(f"{dll} has no pinned checksum")

    if args.engine:
        target = args.engine / "thirdparty" / "amd-fsr-sdk"
        if target.exists():
            shutil.rmtree(target)
        for name in manifest["headers"]:
            if not name.startswith(HEADER_PREFIX):
                raise ValueError(f"Unexpected header location: {name}")
            path = target.joinpath(*safe_member(name.removeprefix(HEADER_PREFIX)).parts)
            path.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(files[name], path)
        for name, license_name in manifest["licenses"].items():
            shutil.copy2(files[name], target / license_name)
        (target / "fsr_sdk_runtime.gen.h").write_text(runtime_header(manifest), encoding="utf-8", newline="\n")
        print(f"Installed AMD FSR SDK {manifest['version']} headers into {target}")

    if args.output:
        args.output.mkdir(parents=True, exist_ok=True)
        for dll in manifest["runtime"]:
            shutil.copy2(files[f"Kits/FidelityFX/signedbin/{dll}"], args.output / dll)
        notices = args.output / "licenses" / "AMD-FidelityFX"
        notices.mkdir(parents=True, exist_ok=True)
        for name, license_name in manifest["licenses"].items():
            shutil.copy2(files[name], notices / license_name)
        print(f"Copied {len(manifest['runtime'])} signed AMD FSR DLLs into {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
