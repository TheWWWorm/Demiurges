#!/usr/bin/env python3
"""Write the English and Russian names of every card for the developer console.

The console's `add spell`, `add creature` and `add enemy` accept a card's name
in either language, whichever language the installed game speaks. The names
come from the wiki encyclopedia (`wiki/catalog/en.json` and `ru.json`, exported
by tools/export_wiki.gd) and are written to `game/src/render/card_names.gd`
(ELCardNames), generated, never edited by hand.

    python3 tools/build_card_names.py            # rebuild
    python3 tools/build_card_names.py --check    # fail if it is stale
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'wiki/catalog'
OUTPUT = ROOT / 'game/src/render/card_names.gd'
KINDS = ('card', 'creature')


def names(lang: str) -> dict:
    data = json.loads((CATALOG / f'{lang}.json').read_text(encoding='utf-8'))
    return {page['card']: page['title'] for page in data['pages'] if page.get('kind') in KINDS and page.get('card')}


def render() -> str:
    english = names('en')
    russian = names('ru')
    lines = [
        '# Generated by tools/build_card_names.py from wiki/catalog; do not edit.',
        'class_name ELCardNames',
        'extends RefCounted',
        '## The English and Russian names of every card of both games, by code, so',
        '## that the developer console finds a card by either name (ELConsoleCards).',
        '',
        'const NAMES := {',
    ]
    for code in sorted(set(english) | set(russian)):
        pair = [english.get(code, ''), russian.get(code, '')]
        lines.append('\t%s: %s,' % (json.dumps(code), json.dumps(pair, ensure_ascii=False)))
    lines.append('}')
    return '\n'.join(lines) + '\n'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true', help='fail if the generated file is stale')
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUTPUT.read_text(encoding='utf-8').replace('\r\n', '\n') if OUTPUT.exists() else ''
        if current != text:
            print(f'{OUTPUT.relative_to(ROOT)} is stale: run tools/build_card_names.py', file=sys.stderr)
            return 1
        print('card names are up to date')
        return 0
    OUTPUT.write_text(text, encoding='utf-8', newline='\n')
    print(f'wrote {OUTPUT.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
